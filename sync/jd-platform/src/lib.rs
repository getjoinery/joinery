//! jd-platform — the operating system, everywhere it is not the filesystem.
//!
//! `jd-vfs` owns the differences between filesystems. This crate owns the rest
//! of them: where a credential is safe, where a config file belongs, how a
//! background program gets started at login, how a URL reaches the user's
//! browser, and how one of the user's own processes reaches another. Five small
//! problems that have three answers each, kept together so that the daemon reads
//! the same on every platform.
//!
//! It also deliberately depends on nothing of the engine. That is what lets the
//! tray — which needs the control channel and none of the rest — be compiled for
//! macOS and Windows from a Linux box, and therefore be checked at all.
//!
//! The rule throughout is the same one the engine follows: **say what actually
//! happened**. A keychain that is not available produces a file and a reported
//! downgrade, not a silent one. An autostart artifact is generated by a pure
//! function so the exact text a Mac will load can be read in a test on Linux —
//! which matters because none of these failures are loud. A malformed plist does
//! not raise an error; it simply never starts.

