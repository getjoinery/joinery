/// What this build calls itself to the server, for the `client_app` identifier
/// and the upgrade gate.
pub const fn client_app() -> &'static str {
    #[cfg(target_os = "macos")]
    {
        "joinery-sync-macos"
    }
    #[cfg(target_os = "windows")]
    {
        "joinery-sync-windows"
    }
    #[cfg(not(any(target_os = "macos", target_os = "windows")))]
    {
        "joinery-sync-linux"
    }
}

/// The platform name the server records on the device row.
pub const fn platform_name() -> &'static str {
    #[cfg(target_os = "macos")]
    {
        "macos"
    }
    #[cfg(target_os = "windows")]
    {
        "windows"
    }
    #[cfg(not(any(target_os = "macos", target_os = "windows")))]
    {
        "linux"
    }
}

/// A name for this device that a person will recognize in a list of devices.
///
/// The machine's own name where it has one, because "MacBook Pro" in the
/// security page is the whole point — a user revoking a lost laptop has to be
/// able to tell which row is the laptop.
pub fn suggested_device_name() -> String {
    for var in ["JOINERY_DEVICE_NAME", "HOSTNAME", "COMPUTERNAME"] {
        if let Ok(v) = std::env::var(var) {
            let v = v.trim();
            if !v.is_empty() {
                return v.to_string();
            }
        }
    }
    // `HOSTNAME` is a shell variable rather than an exported one on most Linux
    // systems, so the file is the reliable source there.
    if let Ok(v) = std::fs::read_to_string("/etc/hostname") {
        let v = v.trim();
        if !v.is_empty() {
            return v.to_string();
        }
    }
    format!("{APP_NAME} ({})", platform_name())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_client_identifier_matches_the_platform_it_was_built_for() {
        assert!(client_app().starts_with("joinery-sync-"));
        assert!(client_app().ends_with(platform_name()));
    }

    #[test]
    fn a_device_name_is_never_empty() {
        // It ends up in conflict-copy filenames, where an empty one produces
        // `Report (conflicted copy 2026-07-31 from ).xlsx`.
        std::env::set_var("JOINERY_DEVICE_NAME", "  ");
        let name = suggested_device_name();
        std::env::remove_var("JOINERY_DEVICE_NAME");
        assert!(!name.trim().is_empty());
    }

    #[test]
    fn an_explicit_device_name_wins() {
        std::env::set_var("JOINERY_DEVICE_NAME", "Kitchen iMac");
        let name = suggested_device_name();
        std::env::remove_var("JOINERY_DEVICE_NAME");
        assert_eq!(name, "Kitchen iMac");
    }
}
